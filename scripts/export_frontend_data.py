"""Export the engine's output as TypeScript files for the Lovable frontend.

Writes frontend_data/src/data/{types,trends,briefs,forecasts}.ts and
frontend_data/src/services/api.ts. Copy the src/ folder into the Lovable
project (or paste the files in): the frontend then shows the engine's real
output, and api.ts switches to the live API as soon as VITE_API_URL is set.

Run from the repo root:  python scripts/export_frontend_data.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import pipeline  # noqa: E402

OUT = ROOT / "frontend_data" / "src"

TYPES = """// Generated by scripts/export_frontend_data.py. Matches the backend API exactly.

export type Trend = {
  id: string;
  name: string;
  category: "colour" | "silhouette" | "detail" | "fabric";
  momentum: number; // -100 to 100
  status: "rising" | "peaking" | "fading";
  evidence: string[];
  weeklyScores: number[]; // last 12 weeks
};

export type DesignBrief = {
  id: string;
  title: string;
  garmentType: "dress" | "top" | "jeans" | "skirt";
  style: "casual" | "classy" | "creative";
  baseDescription: string;
  signatureDetail: string;
  whyNow: string[];
  linkedTrendIds: string[];
  brandDnaFit: number; // 0-100
  targetCustomer: string;
  priceRange: string;
  isMultiway: boolean;
  conversions?: { from: string; to: string; steps: string[] }[];
  isSustainable: boolean;
  sustainabilityNotes?: string[];
  confidence: number; // 0-100
};

export type Forecast = {
  briefId: string;
  weeklyDemand: { week: string; units: number }[];
  recommendedUnits: number;
  sizeSplit: { size: string; percent: number }[];
  launchWindow: string;
  stockRisk: "low" | "medium" | "high";
  riskReason: string;
  // How "recommendedUnits" was set: a newsvendor model on simulated demand.
  demandRange?: { p10: number; p50: number; p90: number }; // simulated season demand
  newsvendor?: {
    criticalRatio: number; // demand percentile ordered to = Cu / (Cu + Co)
    underageCost: number; // $ margin lost per missed sale
    overageCost: number; // $ lost per unsold unit after markdown
    markdownBasis: "evergreen" | "rising" | "peaking" | "fading";
    stockoutProbability: number;
    expectedSellThrough: number;
    expectedLeftoverUnits: number;
    expectedProfit: number;
    simulations: number;
  };
};

export type Overview = {
  risingTrends: number;
  activeBriefs: number;
  totalRecommendedUnits: number;
  averageConfidence: number;
  topBriefIds: string[];
  trendMomentum: { id: string; name: string; momentum: number; status: Trend["status"] }[];
};
"""

API = """// Generated by scripts/export_frontend_data.py.
// Components only call these functions. With VITE_API_URL unset they return the
// bundled data; set it (e.g. to your Render URL) to use the live backend.
import type { DesignBrief, Forecast, Overview, Trend } from "@/data/types";
import { trends } from "@/data/trends";
import { briefs } from "@/data/briefs";
import { forecasts } from "@/data/forecasts";
import { overview } from "@/data/overview";

const API_URL = import.meta.env.VITE_API_URL as string | undefined;

async function get<T>(path: string, fallback: T): Promise<T> {
  if (!API_URL) return fallback;
  const res = await fetch(`${API_URL.replace(/\\/$/, "")}${path}`);
  if (!res.ok) throw new Error(`API ${path} failed: ${res.status}`);
  return (await res.json()) as T;
}

export const getTrends = () => get<Trend[]>("/trends", trends);
export const getBriefs = () => get<DesignBrief[]>("/briefs", briefs);
export const getBriefById = (id: string) =>
  get<DesignBrief | undefined>(`/briefs/${encodeURIComponent(id)}`, briefs.find((b) => b.id === id));
export const getForecasts = () => get<Forecast[]>("/forecasts", forecasts);
export const getForecastByBriefId = (briefId: string) =>
  get<Forecast | undefined>(
    `/forecasts/${encodeURIComponent(briefId)}`,
    forecasts.find((f) => f.briefId === briefId),
  );
export const getOverview = () => get<Overview>("/overview", overview);
"""


def _ts(name: str, type_name: str, data) -> str:
    body = json.dumps(data, indent=2, ensure_ascii=False)
    return (
        "// Generated by scripts/export_frontend_data.py from the backend engine. Do not edit by hand.\n"
        f'import type {{ {type_name.rstrip("[]")} }} from "./types";\n\n'
        f"export const {name}: {type_name} = {body};\n"
    )


def main() -> None:
    snap = pipeline.snapshot()
    (OUT / "data").mkdir(parents=True, exist_ok=True)
    (OUT / "services").mkdir(parents=True, exist_ok=True)

    def dump(models):
        return [m.model_dump(by_alias=True, exclude_none=True) for m in models]

    (OUT / "data" / "types.ts").write_text(TYPES)
    (OUT / "data" / "trends.ts").write_text(_ts("trends", "Trend[]", dump(snap.trends)))
    (OUT / "data" / "briefs.ts").write_text(_ts("briefs", "DesignBrief[]", dump(snap.briefs)))
    (OUT / "data" / "forecasts.ts").write_text(_ts("forecasts", "Forecast[]", dump(snap.forecasts)))
    (OUT / "data" / "overview.ts").write_text(
        _ts("overview", "Overview", snap.overview.model_dump(by_alias=True))
    )
    (OUT / "services" / "api.ts").write_text(API)
    print(f"Wrote {len(snap.trends)} trends, {len(snap.briefs)} briefs, {len(snap.forecasts)} forecasts to {OUT}")


if __name__ == "__main__":
    main()
